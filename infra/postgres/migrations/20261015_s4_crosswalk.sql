-- Migration bổ sung cho cơ sở dữ liệu hiện có. Không tự động thực thi.
-- Repository ứng dụng chỉ cho phép thêm đăng ký/bản phát hành, không ánh xạ lại.
BEGIN;
CREATE TABLE app.canonical_identity (
    canonical_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (canonical_id > 0),
    entity VARCHAR(80) NOT NULL
);
CREATE TABLE app.identity_crosswalk (
    namespace VARCHAR(100) NOT NULL,
    entity VARCHAR(80) NOT NULL,
    source_key VARCHAR(1024) NOT NULL,
    canonical_id BIGINT NOT NULL REFERENCES app.canonical_identity(canonical_id),
    evidence TEXT NOT NULL,
    valid_from VARCHAR(40) NOT NULL,
    valid_to VARCHAR(40),
    PRIMARY KEY (namespace, entity, source_key)
);
CREATE TABLE app.crosswalk_release (
    version VARCHAR(100) PRIMARY KEY,
    fingerprint VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL
);
COMMIT;
