from __future__ import annotations

from pathlib import Path

import pytest
from openpyxl import Workbook

from app.modules.ingestion.readers.contract import ReadRequest
from app.modules.ingestion.readers.excel_reader import ExcelReader


def _excel_request(location: str, source_table: str | None = None) -> ReadRequest:
    """Tạo request Excel hợp lệ để các test không lặp lại cấu hình."""

    return ReadRequest(
        source_type="EXCEL",
        location=location,
        configuration={
            "sheet_name": "Applicants",
            "header_row": 1,
            "skip_rows": 0,
        },
        source_table=source_table,
    )


def _write_workbook(path: Path, rows: list[list[object | None]], sheet_name: str) -> None:
    """Tạo workbook test nhỏ và lưu xuống file tạm."""

    workbook = Workbook()
    sheet = workbook.active
    assert sheet is not None
    sheet.title = sheet_name

    # Mỗi phần tử trong rows là một dòng Excel cần ghi.
    for row in rows:
        assert sheet is not None
        sheet.append(row)

    workbook.save(path)
    workbook.close()


def test_excel_reader_success(tmp_path: Path) -> None:
    """Đọc Excel thành công khi location là thư mục và source_table là tên file."""

    # 1. Tạo file Excel giả lập trong thư mục tạm của pytest.
    excel_file = tmp_path / "applicant.xlsx"
    _write_workbook(
        excel_file,
        [
            ["applicant_id", "full_name"],
            [1, "Nguyen Van A"],
            [2, "Tran Thi B"],
        ],
        sheet_name="Applicants",
    )

    # 2. Tạo request giống tình huống data source trỏ tới một thư mục ingest.
    request = _excel_request(str(tmp_path), source_table="applicant.xlsx")

    # 3. Gọi ExcelReader để parse sheet bằng openpyxl.
    result = ExcelReader().read(request)

    # 4. Kiểm tra cột, số dòng, dữ liệu và metadata nguồn trả về.
    assert result.columns == ["applicant_id", "full_name"]
    assert result.rows == [
        (1, "Nguyen Van A"),
        (2, "Tran Thi B"),
    ]
    assert result.rows_read == 2
    assert result.source_table == "applicant.xlsx"


def test_excel_reader_success_when_location_is_file_and_skips_metadata(
    tmp_path: Path,
) -> None:
    """Đọc Excel thành công khi location trỏ thẳng tới file và có dòng metadata."""

    excel_file = tmp_path / "major.xlsx"
    _write_workbook(
        excel_file,
        [
            ["Generated by UniLake"],
            ["major_id", "major_name"],
            [1, "Software Engineering"],
        ],
        sheet_name="Applicants",
    )

    request = _excel_request(str(excel_file))
    request.configuration["skip_rows"] = 1

    result = ExcelReader().read(request)

    assert result.columns == ["major_id", "major_name"]
    assert result.rows == [(1, "Software Engineering")]
    assert result.rows_read == 1
    assert result.source_table == "major.xlsx"


def test_excel_reader_file_not_found(tmp_path: Path) -> None:
    """Báo lỗi rõ ràng khi source_table không tồn tại trong thư mục."""

    request = _excel_request(str(tmp_path), source_table="not_found.xlsx")

    with pytest.raises(FileNotFoundError):
        ExcelReader().read(request)


def test_excel_reader_invalid_configuration(tmp_path: Path) -> None:
    """Báo lỗi sớm khi header_row không hợp lệ."""

    request = _excel_request(str(tmp_path), source_table="applicant.xlsx")
    request.configuration["header_row"] = 0

    with pytest.raises(ValueError, match="header_row phải >= 1"):
        ExcelReader().read(request)


def test_excel_reader_rejects_nested_source_table(tmp_path: Path) -> None:
    """Không cho source_table chứa đường dẫn con khi location là thư mục."""

    # Rule này tránh caller truyền "../file.xlsx" hoặc "subdir/file.xlsx"
    # khiến reader đọc nhầm file ngoài thư mục nguồn đã đăng ký.
    request = _excel_request(str(tmp_path), source_table="nested/applicant.xlsx")

    with pytest.raises(ValueError, match="source_table không hợp lệ"):
        ExcelReader().read(request)


def test_excel_reader_rejects_missing_sheet(tmp_path: Path) -> None:
    """Báo lỗi khi workbook không có sheet được cấu hình."""

    excel_file = tmp_path / "applicant.xlsx"
    _write_workbook(
        excel_file,
        [["applicant_id", "full_name"], [1, "Nguyen Van A"]],
        sheet_name="DifferentSheet",
    )

    request = _excel_request(str(excel_file))

    with pytest.raises(ValueError, match="Không tìm thấy sheet: Applicants"):
        ExcelReader().read(request)


def test_excel_reader_rejects_empty_header_cell(tmp_path: Path) -> None:
    """Header không được có ô trống ở giữa danh sách cột."""

    excel_file = tmp_path / "applicant.xlsx"
    _write_workbook(
        excel_file,
        [["applicant_id", None, "full_name"], [1, None, "Nguyen Van A"]],
        sheet_name="Applicants",
    )

    request = _excel_request(str(excel_file))

    with pytest.raises(ValueError, match="Header chứa tên cột trống"):
        ExcelReader().read(request)


def test_excel_reader_rejects_duplicate_header(tmp_path: Path) -> None:
    """Header không được có tên cột trùng nhau."""

    excel_file = tmp_path / "applicant.xlsx"
    _write_workbook(
        excel_file,
        [["applicant_id", "applicant_id"], [1, 2]],
        sheet_name="Applicants",
    )

    request = _excel_request(str(excel_file))

    with pytest.raises(ValueError, match="Header chứa tên cột trùng nhau"):
        ExcelReader().read(request)
